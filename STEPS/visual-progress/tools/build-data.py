#!/usr/bin/env python3
"""Validate data/steps/*.json and regenerate data/steps.json + data/steps.js.

Python 3 stdlib only. Files starting with "_" (e.g. _template.json) are skipped.
Usage: python3 STEPS/visual-progress/tools/build-data.py
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "steps")
STATUSES = {"done", "in-progress", "planned", "blocked"}
DATE_RE = re.compile(r"^(\d{4}-\d{2}-\d{2}|TBD)$")
errors = []


def err(f, msg):
    errors.append(f"{f}: {msg}")


def check(f, s):
    if not isinstance(s, dict):
        return err(f, "top level must be an object")
    for k in ("id", "title", "date", "status"):
        if not isinstance(s.get(k), str) or not s[k]:
            err(f, f"missing/empty string '{k}'")
    if s.get("id") != f[:-5]:
        err(f, "id must equal the file name without .json")
    if isinstance(s.get("date"), str) and not DATE_RE.match(s["date"]):
        err(f, "date must be YYYY-MM-DD or TBD")
    if s.get("status") not in STATUSES:
        err(f, f"status must be one of {sorted(STATUSES)}")
    c = s.get("commit")
    if s.get("status") == "done":
        if not (isinstance(c, dict) and c.get("hash") and c.get("date")):
            err(f, "done steps need commit.hash and commit.date (from git)")
        elif not DATE_RE.match(c["date"]):
            err(f, "commit.date must be YYYY-MM-DD")
    elif c is not None:
        err(f, "commit must be null unless status is done")
    for k in ("added", "removed", "changed"):
        if not isinstance(s.get(k, []), list) or not all(isinstance(x, str) for x in s.get(k, [])):
            err(f, f"'{k}' must be a list of strings")
    for x in s.get("files", []):
        if not (isinstance(x, dict) and isinstance(x.get("path"), str)):
            err(f, "files entries need a 'path'")
    for x in s.get("sources", []):
        if not (isinstance(x, dict) and isinstance(x.get("name"), str)):
            err(f, "sources entries need a 'name'")
    sh = s.get("screenshot")
    if sh:
        if not os.path.isfile(os.path.join(ROOT, sh)):
            err(f, f"screenshot file not found: {sh}")


def main():
    steps, seen = [], set()
    for f in sorted(os.listdir(SRC)):
        if not f.endswith(".json") or f.startswith("_"):
            continue
        try:
            with open(os.path.join(SRC, f), encoding="utf-8") as fh:
                s = json.load(fh)
        except Exception as e:
            err(f, f"invalid JSON: {e}")
            continue
        check(f, s)
        if isinstance(s, dict):
            if s.get("id") in seen:
                err(f, "duplicate id")
            seen.add(s.get("id"))
            steps.append(s)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        print(f"{len(errors)} error(s); nothing written", file=sys.stderr)
        return 1
    data = {"steps": steps}
    text = json.dumps(data, ensure_ascii=False, indent=1)
    with open(os.path.join(ROOT, "data", "steps.json"), "w", encoding="utf-8") as fh:
        fh.write(text + "\n")
    with open(os.path.join(ROOT, "data", "steps.js"), "w", encoding="utf-8") as fh:
        fh.write("// generated by tools/build-data.py, do not edit\nwindow.STEPS_DATA = " + text + ";\n")
    print(f"ok: {len(steps)} steps")
    return 0


sys.exit(main())
